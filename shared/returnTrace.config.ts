const TITLES = ['Одинаковая квитанция', 'Канал сообщений', 'Источник шаблонов'];

/** Generate only missing snapshots; existing archive entries remain immutable. */
export function buildReturnCaseScenes(savedKeys: ReadonlySet<string>, evidence: readonly ReturnEvidence[]): ReturnScene[] {
  const scenes: ReturnScene[] = [];
  if (!savedKeys.has(RETURN_CASE_INTRO_KEY)) scenes.push({ entry_key: RETURN_CASE_INTRO_KEY, category: 'story', position: 1001, content: { title: 'Обращение Миры', text: INTRO } });
  let previousOpen: boolean = true;
  for (let i = 0; i < RETURN_CASE_STAGES.length; i++) {
    const stage = RETURN_CASE_STAGES[i];
    const saved = savedKeys.has(stage.key);
    const match = stage.missions.find(key => evidence.some(item => item.mission_key === key && item.outcome === 'success'));
    const open: boolean = previousOpen && (saved || !!match);
    if (open && !saved && match) scenes.push({ entry_key: stage.key, category: 'story', position: 1002 + i,
      content: { title: TITLES[i], text: `${DETAILS[match]}\n\n${STAGE_TEXT[i]}`, sourceMission: match } });
    previousOpen = open;
  }
  return scenes;
}

export function getReturnCaseProgress(keys: ReadonlySet<string>) {
  let completed = 0;
  for (const stage of RETURN_CASE_STAGES) {
    if (!keys.has(stage.key)) break;
    completed++;
  }
  return { completed, next: RETURN_CASE_STAGES[completed] ?? null };
}
