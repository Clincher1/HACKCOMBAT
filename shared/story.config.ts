export const STORY_EPISODES: readonly StoryEpisode[] = stories.map(([title, text], index) => ({
  id: index + 1,
  season: Math.floor(index / 6) + 1,
  title,
  missions: 2 + index * 2,
  text,
}));

export function getStoryState(player: PlayerState) {
  const introComplete = getFirstChapterState(player).complete;
  const totalMissions = Math.max(0, Math.floor(Number.isFinite(player.totalMissions) ? player.totalMissions : 0));
  const unlocked = introComplete ? STORY_EPISODES.filter(episode => totalMissions >= episode.missions) : [];
  return { introComplete, totalMissions, unlocked, next: introComplete ? STORY_EPISODES[unlocked.length] ?? null : null };
}
