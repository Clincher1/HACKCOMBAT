/** Короткая подпись под кнопкой: «Сейчас ×4 · следом ×8». */
export function prestigeBonusLabel(currentCount: number, nextCount: number): string {
  return `Сейчас ×${formatPrestigeMultiplier(currentCount)} · следом ×${formatPrestigeMultiplier(nextCount)}`;
}

/** Множитель для человека: 32 → «×32», 1.1 → «×1.1». */
export function formatPrestigeMultiplier(multiplier: number): string {
  const safe = Number(multiplier) || 1;
  const rounded = Math.round(safe * 10) / 10;
  return Number.isInteger(rounded) ? String(rounded) : rounded.toFixed(1);
}
