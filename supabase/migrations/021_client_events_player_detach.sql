-- ============================================================================
-- HACKER KOMBAT — Миграция 021: обезличивание client_events под вайп v1
-- ----------------------------------------------------------------------------
-- Зачем: v1 (2026-11-28) — точка запуска. Вайп стирает прогресс игроков
-- (scripts/wipe-players.mjs), но аналитика по дням должна выжить: воронка,
-- ошибки клиента и метрики по дням считаются по client_events.
--
-- Проблема: в 019 колонка player_id объявлена NOT NULL с ON DELETE CASCADE.
-- Порядок «отвязать телеметрию, потом удалить игроков» невозможен (нельзя
-- записать NULL), а порядок «удалить игроков, потом отвязать» уносит события
-- каскадом — статистика пропадает.
--
-- Решение: снимаем NOT NULL. Семантика прежняя:
--   player_id = uuid  → событие принадлежит живому игроку (как раньше);
--   player_id = NULL  → событие обезличено вайпом (строка остаётся в аналитике).
-- FK и ON DELETE CASCADE сохраняются: новые игроки пишутся как обычно, а
-- удаление игрока по-прежнему убирает его собственные события.
--
-- Аддитивно и обратимо: приложение пишет player_id всегда, поэтому на API и
-- клиент ничего не влияет. Построчные данные не меняются.
-- ============================================================================

ALTER TABLE public.client_events
  ALTER COLUMN player_id DROP NOT NULL;

COMMENT ON COLUMN public.client_events.player_id IS
  'uuid игрока; NULL = событие обезличено вайпом v1 (2026-11-28). Аналитика по дням сохраняется.';
